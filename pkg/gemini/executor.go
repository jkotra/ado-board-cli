func (e *Executor) executeTrackQuery(args map[string]any) (map[string]any, error) {
	queryInput, _ := args["query_id_or_url"].(string)
	queryInput = strings.TrimSpace(queryInput)
	if queryInput == "" {
		return nil, fmt.Errorf("missing required parameter: query_id_or_url")
	}
	name, _ := args["name"].(string)

	if e.AdoClient == nil {
		return nil, fmt.Errorf("ADO client is not configured")
	}

	target, err := ado.ParseTrackTarget(queryInput, e.AdoClient.Org, e.AdoClient.Project)
	if err != nil || target.Type != ado.TrackTargetQuery {
		return nil, fmt.Errorf("invalid query identifier or URL: %s", queryInput)
	}

	qInfo, rootIDs, items, err := e.AdoClient.FetchQueryHierarchy(target.QueryID)
	if err != nil {
		return nil, fmt.Errorf("failed to fetch query: %w", err)
	}

	queryName := qInfo.Name
	if name != "" {
		queryName = name
	}

	project := target.Project
	if project == "" {
		project = e.AdoClient.Project
	}
	org := target.Org
	if org == "" {
		org = e.AdoClient.Org
	}

	if err := e.DB.SaveTrackedQuery(qInfo.ID, queryName, qInfo.Path, org, project, target.RawURL, qInfo.QueryType); err != nil {
		return nil, fmt.Errorf("failed to save tracked query: %w", err)
	}

	for _, rID := range rootIDs {
		_ = e.DB.SaveTrackedRootWithQuery(rID, org, project, "", qInfo.ID)
		e.AffectedIDs[rID] = true
	}

	if len(items) > 0 {
		_ = e.DB.SaveWorkItems(org, project, items)
	}

	return map[string]any{
		"success":          true,
		"query_id":         qInfo.ID,
		"query_name":       queryName,
		"query_type":       qInfo.QueryType,
		"total_root_items": len(rootIDs),
		"total_work_items": len(items),
		"message":          fmt.Sprintf("Successfully tracked query '%s' (%d root items, %d total items)", queryName, len(rootIDs), len(items)),
	}, nil
}

