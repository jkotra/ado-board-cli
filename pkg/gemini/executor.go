func toStringSlice(val any) []string {
	if val == nil {
		return nil
	}
	switch v := val.(type) {
	case []string:
		return v
	case []any:
		var res []string
		for _, item := range v {
			if s, ok := item.(string); ok && strings.TrimSpace(s) != "" {
				res = append(res, strings.TrimSpace(s))
			}
		}
		return res
	case string:
		if strings.TrimSpace(v) == "" {
			return nil
		}
		parts := strings.Split(v, ",")
		var res []string
		for _, p := range parts {
			if s := strings.TrimSpace(p); s != "" {
				res = append(res, s)
			}
		}
		return res
	default:
		return nil
	}
}

func (e *Executor) resolveReviewer(input string, isRequired bool) ado.ReviewerInput {
	input = strings.TrimSpace(input)
	if input == "" {
		return ado.ReviewerInput{}
	}

	// 1. If it's already a GUID
	if len(input) == 36 && strings.Count(input, "-") == 4 {
		return ado.ReviewerInput{
			ID:         input,
			IsRequired: isRequired,
		}
	}

	// 2. Search DB identities for matching display name or email to get identity GUID
	if e.DB != nil {
		if identities, err := e.DB.SearchIdentities(input, 10); err == nil && len(identities) > 0 {
			for _, id := range identities {
				if strings.EqualFold(id.DisplayName, input) || strings.EqualFold(id.Email, input) {
					return ado.ReviewerInput{
						ID:          id.ID,
						DisplayName: id.DisplayName,
						UniqueName:  id.Email,
						IsRequired:  isRequired,
					}
				}
			}
			return ado.ReviewerInput{
				ID:          identities[0].ID,
				DisplayName: identities[0].DisplayName,
				UniqueName:  identities[0].Email,
				IsRequired:  isRequired,
			}
		}
	}

	// 3. Check cached identities in context
	if e.Context != nil {
		for _, id := range e.Context.CachedIdentities {
			if strings.EqualFold(id.DisplayName, input) || strings.EqualFold(id.Email, input) ||
				strings.Contains(strings.ToLower(id.DisplayName), strings.ToLower(input)) {
				return ado.ReviewerInput{
					DisplayName: id.DisplayName,
					UniqueName:  id.Email,
					IsRequired:  isRequired,
				}
			}
		}
	}

	// 4. Resolve email using DB.ResolveAssignee
	if e.DB != nil {
		if email, isUnassign := e.DB.ResolveAssignee(input); !isUnassign && email != "" {
			return ado.ReviewerInput{
				UniqueName: email,
				IsRequired: isRequired,
			}
		}
	}

	return ado.ReviewerInput{
		UniqueName: input,
		IsRequired: isRequired,
	}
}

func (e *Executor) executeCreatePullRequest(args map[string]any) (map[string]any, error) {
	if e.AdoClient == nil {
		return nil, fmt.Errorf("ADO client not initialized")
	}

	sourceBranch := getString(args, "source_branch")
	if sourceBranch == "" {
		return nil, fmt.Errorf("missing required parameter: source_branch")
	}

	title := getString(args, "title")
	if title == "" {
		return nil, fmt.Errorf("missing required parameter: title")
	}

	targetBranch := getString(args, "target_branch")
	description := getString(args, "description")
	repoID := getString(args, "repository_id")
	isDraft := getBool(args, "is_draft")

	var reviewerInputs []ado.ReviewerInput
	for _, r := range toStringSlice(args["reviewers"]) {
		if rev := e.resolveReviewer(r, false); rev.ID != "" || rev.UniqueName != "" {
			reviewerInputs = append(reviewerInputs, rev)
		}
	}
	for _, r := range toStringSlice(args["required_reviewers"]) {
		if rev := e.resolveReviewer(r, true); rev.ID != "" || rev.UniqueName != "" {
			reviewerInputs = append(reviewerInputs, rev)
		}
	}

	var wiRefs []ado.PRWorkItemRef
	var wiID int
	if wiVal, ok := args["work_item_id"]; ok && wiVal != nil {
		wiID = toInt(wiVal)
		if wiID > 0 {
			wiRefs = append(wiRefs, ado.PRWorkItemRef{ID: fmt.Sprintf("%d", wiID)})
		}
	}

	params := ado.CreatePullRequestParams{
		SourceRefName: sourceBranch,
		TargetRefName: targetBranch,
		Title:         title,
		Description:   description,
		IsDraft:       isDraft,
		Reviewers:     reviewerInputs,
		WorkItemRefs:  wiRefs,
	}

	pr, err := e.AdoClient.CreatePullRequest(repoID, params)
	if err != nil {
		return nil, err
	}

	org := e.AdoClient.Org
	project := e.AdoClient.Project
	repoName := ""
	if pr.Repository != nil {
		repoName = pr.Repository.Name
	}

	if e.DB != nil {
		_ = e.DB.SavePullRequest(pr, org, project)
		if wiID > 0 {
			_ = e.DB.LinkWorkItemPullRequest(wiID, pr.PullRequestID)
			e.AffectedIDs[wiID] = true
		}
	}

	webURL := ado.BuildPRWebURL(org, project, repoName, pr.PullRequestID)

	return map[string]any{
		"status":          "success",
		"pull_request_id": pr.PullRequestID,
		"title":           pr.Title,
		"description":     pr.Description,
		"source_branch":   pr.SourceBranch(),
		"target_branch":   pr.TargetBranch(),
		"status_name":     pr.Status,
		"is_draft":        pr.IsDraft,
		"url":             webURL,
		"message":         fmt.Sprintf("Successfully created Pull Request #%d: '%s' (%s -> %s)", pr.PullRequestID, pr.Title, pr.SourceBranch(), pr.TargetBranch()),
	}, nil
}

