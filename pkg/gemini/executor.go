func (e *Executor) executeGetActivity(args map[string]any) (map[string]any, error) {
	idVal := args["work_item_id"]
	id := toInt(idVal)
	if id == 0 && e.Context.SelectedItem != nil {
		id = e.Context.SelectedItem.ID
	}

	timeRange := getString(args, "time_range")
	sinceDays := toInt(args["since_days"])
	includeChildren := true
	if ic, ok := args["include_children"].(bool); ok {
		includeChildren = ic
	}

	since, until := ado.ParseTimeRange(timeRange, sinceDays)

	var rootItem *ado.WorkItem
	if id > 0 && e.AdoClient != nil {
		rootItem, _ = e.AdoClient.GetWorkItem(id)
	}

	itemIDs := []int{}
	if id > 0 {
		itemIDs = append(itemIDs, id)
	} else if e.DB != nil {
		if allRecs, err := e.DB.GetAllWorkItems(); err == nil {
			for _, r := range allRecs {
				itemIDs = append(itemIDs, r.ID)
			}
		}
	}

	if includeChildren && id > 0 {
		if rootItem != nil {
			itemIDs = append(itemIDs, rootItem.ChildIDs()...)
		} else if e.DB != nil {
			if chRecs, err := e.DB.GetChildWorkItems(id); err == nil {
				for _, ch := range chRecs {
					itemIDs = append(itemIDs, ch.ID)
				}
			}
		}
	}

	// Deduplicate IDs
	uniqueIDs := make([]int, 0, len(itemIDs))
	seenIDs := make(map[int]bool)
	for _, itemID := range itemIDs {
		if !seenIDs[itemID] {
			seenIDs[itemID] = true
			uniqueIDs = append(uniqueIDs, itemID)
		}
	}

	var allEvents []*ado.ActivityEvent
	var mu sync.Mutex
	var wg sync.WaitGroup
	sem := make(chan struct{}, 6)

	for _, itemID := range uniqueIDs {
		wg.Add(1)
		go func(wID int) {
			defer wg.Done()
			sem <- struct{}{}
			defer func() { <-sem }()

			var wi *ado.WorkItem
			if wID == id && rootItem != nil {
				wi = rootItem
			} else if e.AdoClient != nil {
				wi, _ = e.AdoClient.GetWorkItem(wID)
			}

			var itemEvents []*ado.ActivityEvent

			// 1. Fetch live updates from ADO if client is available
			if e.AdoClient != nil {
				updates, err := e.AdoClient.GetWorkItemUpdates(wID)
				if err == nil && len(updates) > 0 {
					itemEvents = append(itemEvents, ado.ParseUpdatesToEvents(wi, updates)...)
				}
			}

			// 2. Fetch comments from DB / ADO
			if e.DB != nil {
				dbComments, err := e.DB.GetComments(wID)
				if err == nil {
					for _, c := range dbComments {
						if c.CreatedDate.IsZero() {
							continue
						}
						cTime := c.CreatedDate.Local()
						// Avoid duplicates if already captured via System.History updates
						alreadyCaptured := false
						for _, ev := range itemEvents {
							if ev.Type == ado.ActivityComment && (ev.Timestamp.Equal(cTime) || (ev.Details != "" && strings.Contains(c.Text, ev.Details))) {
								alreadyCaptured = true
								break
							}
						}
						if !alreadyCaptured {
							itemTitle := ""
							itemType := ""
							if wi != nil {
								itemTitle = wi.Title()
								itemType = wi.Type()
							}
							itemEvents = append(itemEvents, &ado.ActivityEvent{
								Timestamp:      cTime,
								DateString:     ado.FormatDateHeader(cTime),
								TimeOnlyString: ado.FormatTimeOnly(cTime),
								TimeString:     cTime.Format("2006-01-02 15:04:05 MST"),
								RelativeTime:   ado.FormatRelativeTime(cTime),
								WorkItemID:     wID,
								WorkItemTitle:  itemTitle,
								WorkItemType:   itemType,
								Type:           ado.ActivityComment,
								AuthorName:     c.AuthorName,
								AuthorEmail:    c.AuthorEmail,
								Summary:        fmt.Sprintf("%s commented on #%d", c.AuthorName, wID),
								Details:        ado.CleanHTML(c.Text),
								NewValue:       ado.CleanHTML(c.Text),
							})
						}
					}
				}

				// 3. Check linked pull requests from DB
				prs, err := e.DB.GetPullRequestsForWorkItem(wID)
				if err == nil {
					for _, pr := range prs {
						if pr != nil {
							prTime := pr.LastSyncedAt.Local()
							alreadyCaptured := false
							for _, ev := range itemEvents {
								if ev.Type == ado.ActivityPullRequest && ev.PullRequestID == pr.ID {
									alreadyCaptured = true
									if pr.URL != "" {
										ev.PullRequestURL = pr.URL
									}
									if pr.Title != "" {
										ev.Details = fmt.Sprintf("Title: %s\nStatus: %s\nSource: %s\nTarget: %s\nURL: %s", pr.Title, pr.Status, pr.SourceBranch, pr.TargetBranch, pr.URL)
									}
									break
								}
							}
							if !alreadyCaptured {
								itemTitle := ""
								itemType := ""
								if wi != nil {
									itemTitle = wi.Title()
									itemType = wi.Type()
								}
								itemEvents = append(itemEvents, &ado.ActivityEvent{
									Timestamp:      prTime,
									DateString:     ado.FormatDateHeader(prTime),
									TimeOnlyString: ado.FormatTimeOnly(prTime),
									TimeString:     prTime.Format("2006-01-02 15:04:05 MST"),
									RelativeTime:   ado.FormatRelativeTime(prTime),
									WorkItemID:     wID,
									WorkItemTitle:  itemTitle,
									WorkItemType:   itemType,
									Type:           ado.ActivityPullRequest,
									AuthorName:     pr.CreatedByName,
									AuthorEmail:    pr.CreatedByEmail,
									Summary:        fmt.Sprintf("%s linked Pull Request #%d: %s [%s → %s] (Status: %s)", pr.CreatedByName, pr.ID, pr.Title, pr.SourceBranch, pr.TargetBranch, pr.Status),
									Details:        fmt.Sprintf("Title: %s\nStatus: %s\nSource: %s\nTarget: %s\nURL: %s", pr.Title, pr.Status, pr.SourceBranch, pr.TargetBranch, pr.URL),
									PullRequestID:  pr.ID,
									PullRequestURL: pr.URL,
								})
							}
						}
					}
				}
			}

			// Fallback: Ensure all PR events have a valid web URL
			for _, ev := range itemEvents {
				if ev.Type == ado.ActivityPullRequest && ev.PullRequestID > 0 {
					if ev.PullRequestURL == "" || strings.HasPrefix(ev.PullRequestURL, "vstfs:") {
						if e.AdoClient != nil && e.AdoClient.Org != "" && e.AdoClient.Project != "" {
							ev.PullRequestURL = fmt.Sprintf("https://dev.azure.com/%s/%s/_git/pullrequest/%d", e.AdoClient.Org, e.AdoClient.Project, ev.PullRequestID)
						}
					}
				}
			}

			mu.Lock()
			allEvents = append(allEvents, itemEvents...)
			mu.Unlock()
		}(itemID)
	}

	wg.Wait()

	sortedEvents := ado.SortAndFilterEvents(allEvents, since, until)

	commentsCount := 0
	stateChangesCount := 0
	prsCount := 0
	for _, ev := range sortedEvents {
		switch ev.Type {
		case ado.ActivityComment:
			commentsCount++
		case ado.ActivityStateChange:
			stateChangesCount++
		case ado.ActivityPullRequest:
			prsCount++
		}
	}

	title := ""
	itemType := ""
	if rootItem != nil {
		title = rootItem.Title()
		itemType = rootItem.Type()
	} else if e.Context.SelectedItem != nil && e.Context.SelectedItem.ID == id {
		title = e.Context.SelectedItem.Title
		itemType = e.Context.SelectedItem.Type
	} else if e.DB != nil && id > 0 {
		if rec, err := e.DB.GetWorkItem(id); err == nil && rec != nil {
			title = rec.Title
			itemType = rec.WorkItemType
		}
	}

	return map[string]any{
		"status":              "success",
		"work_item_id":        id,
		"work_item_title":     title,
		"work_item_type":      itemType,
		"time_range":          timeRange,
		"since":               since.Format("2006-01-02 15:04:05"),
		"until":               until.Format("2006-01-02 15:04:05"),
		"total_events":        len(sortedEvents),
		"comments_count":      commentsCount,
		"state_changes_count": stateChangesCount,
		"prs_count":           prsCount,
		"events":              sortedEvents,
	}, nil
}

