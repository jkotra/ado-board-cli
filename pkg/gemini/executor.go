func parseFlexibleDateField(val any) (string, bool) {
	if val == nil {
		return "", false
	}
	s, ok := val.(string)
	if !ok {
		return "", false
	}
	s = strings.TrimSpace(s)
	if s == "" {
		return "", true // explicitly clear
	}
	if t, ok := ado.ParseDateOrDateTime(s, time.Now()); ok {
		return ado.FormatAdoDateTime(t), true
	}
	return s, true
}

// Executor executes tool calls generated by the Gemini model
type Executor struct {
	AdoClient       *ado.Client
	DB              *db.DB
	Context         *ContextPayload
	Confirm         ConfirmCallback
	AffectedIDs     map[int]bool
	SettingsUpdated bool
}

// NewExecutor creates a new tool executor
func NewExecutor(adoClient *ado.Client, database *db.DB, ctx *ContextPayload, confirm ConfirmCallback) *Executor {
	if adoClient != nil && database != nil {
		adoClient.SetIdentityResolver(func(q string) *ado.IdentityRef {
			if id, err := database.FindIdentity(q); err == nil && id != nil {
				return &ado.IdentityRef{
					ID:          id.ID,
					DisplayName: id.DisplayName,
					UniqueName:  id.Email,
				}
			}
			return nil
		})
		if ids, err := database.GetAllIdentities(); err == nil && len(ids) > 0 {
			refs := make([]*ado.IdentityRef, 0, len(ids))
			for _, id := range ids {
				refs = append(refs, &ado.IdentityRef{
					ID:          id.ID,
					DisplayName: id.DisplayName,
					UniqueName:  id.Email,
				})
			}
			adoClient.RegisterIdentities(refs...)
		}
	}
	return &Executor{
		AdoClient:   adoClient,
		DB:          database,
		Context:     ctx,
		Confirm:     confirm,
		AffectedIDs: make(map[int]bool),
	}
}

// GetAffectedIDs returns all work item IDs that were modified during execution
func (e *Executor) GetAffectedIDs() []int {
	var ids []int
	for id := range e.AffectedIDs {
		ids = append(ids, id)
	}
	return ids
}

// resolveAssignee attempts to match an input string (name or email fragment) to a known identity
func (e *Executor) resolveAssignee(input string) string {
	input = strings.TrimSpace(input)
	if input == "" {
		return ""
	}
	if strings.EqualFold(input, "unassigned") || strings.EqualFold(input, "none") || strings.EqualFold(input, "[all]") {
		return ""
	}

	// 1. Check DB resolver if DB available
	if e.DB != nil {
		res, isUnassign := e.DB.ResolveAssignee(input)
		if isUnassign {
			return ""
		}
		if res != "" && (strings.Contains(res, "@") || strings.Contains(res, " ")) {
			return res
		}
	}

	lower := strings.ToLower(input)

	// 2. Check cached identities in Context
	if e.Context != nil {
		for _, id := range e.Context.CachedIdentities {
			if strings.EqualFold(id.Email, input) {
				return id.Email
			}
			if strings.EqualFold(id.DisplayName, input) {
				return id.Email
			}
			if strings.Contains(strings.ToLower(id.DisplayName), lower) || strings.Contains(strings.ToLower(id.Email), lower) {
				return id.Email
			}
		}
	}
	return input
}

// Execute parses and runs the given function name with provided arguments
func (e *Executor) Execute(name string, args map[string]any) (map[string]any, error) {
	start := time.Now()
	res, err := e.executeInternal(name, args)
	dur := time.Since(start)
	if err != nil {
		slog.Error("Gemini Tool Execution Failed",
			slog.String("tool", name),
			slog.Int64("duration_ms", dur.Milliseconds()),
			slog.Any("error", err),
		)
	} else {
		slog.Debug("Gemini Tool Executed",
			slog.String("tool", name),
			slog.Int64("duration_ms", dur.Milliseconds()),
		)
	}
	return res, err
}

