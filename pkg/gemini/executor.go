func (e *Executor) executeTrackWorkItem(args map[string]any) (map[string]any, error) {
	idVal, ok := args["work_item_id"]
	if !ok {
		return nil, fmt.Errorf("missing required parameter: work_item_id")
	}
	id := toInt(idVal)
	if id == 0 {
		return nil, fmt.Errorf("invalid work_item_id")
	}

	customTitle, _ := args["custom_title"].(string)

	if e.AdoClient == nil {
		return nil, fmt.Errorf("ADO client is not configured")
	}

	items, err := e.AdoClient.FetchHierarchy(id)
	if err != nil {
		return nil, fmt.Errorf("failed to fetch hierarchy for #%d: %w", id, err)
	}
	if len(items) == 0 {
		return nil, fmt.Errorf("no work items found for #%d", id)
	}

	project := e.AdoClient.Project
	if project == "" && len(items) > 0 {
		project = items[0].GetStringField("System.TeamProject")
	}
	org := e.AdoClient.Org

	if err := e.DB.SaveTrackedRoot(id, org, project, ""); err != nil {
		return nil, fmt.Errorf("failed to save tracked root: %w", err)
	}
	if customTitle != "" {
		_ = e.DB.UpdateTrackedRootCustomTitle(id, customTitle)
	}

	if err := e.DB.SaveWorkItems(org, project, items); err != nil {
		return nil, fmt.Errorf("failed to save work items: %w", err)
	}

	e.AffectedIDs[id] = true

	rootTitle := items[0].Title()
	rootType := items[0].Type()

	return map[string]any{
		"success":        true,
		"work_item_id":   id,
		"title":          rootTitle,
		"type":           rootType,
		"custom_title":   customTitle,
		"total_imported": len(items),
		"message":        fmt.Sprintf("Successfully tracked %s #%d (%s) with %d items in hierarchy", rootType, id, rootTitle, len(items)),
	}, nil
}

