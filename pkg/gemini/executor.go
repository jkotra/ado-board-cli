func (e *Executor) executeGetWorkItemDetails(args map[string]any) (map[string]any, error) {
	idVal, ok := args["work_item_id"]
	if !ok {
		return nil, fmt.Errorf("missing required parameter: work_item_id")
	}
	id := toInt(idVal)
	if id == 0 && e.Context != nil && e.Context.SelectedItem != nil {
		id = e.Context.SelectedItem.ID
	}
	if id <= 0 {
		return nil, fmt.Errorf("invalid work_item_id: %v", idVal)
	}

	var item *ado.WorkItem
	var fetchErr error
	if e.AdoClient != nil {
		item, fetchErr = e.AdoClient.GetWorkItem(id)
		if fetchErr == nil && item != nil && e.DB != nil {
			_ = e.DB.SaveWorkItem(e.AdoClient.Org, e.AdoClient.Project, item)
		}
	}

	var rec *db.WorkItemRecord
	if e.DB != nil {
		rec, _ = e.DB.GetWorkItem(id)
	}

	if item == nil && rec == nil {
		if fetchErr != nil {
			return nil, fmt.Errorf("failed to fetch item #%d: %w", id, fetchErr)
		}
		return nil, fmt.Errorf("work item #%d not found", id)
	}

	var children []*db.WorkItemRecord
	if e.DB != nil {
		children, _ = e.DB.GetChildWorkItems(id)
	}

	var childSummaries []map[string]any
	for _, ch := range children {
		childSummaries = append(childSummaries, map[string]any{
			"id":                ch.ID,
			"type":              ch.WorkItemType,
			"title":             ch.Title,
			"state":             ch.State,
			"assigned_to":       ch.AssignedToName,
			"activity":          ch.Activity,
			"original_estimate": ch.OriginalEstimate,
			"remaining_work":    ch.RemainingWork,
			"completed_work":    ch.CompletedWork,
			"effort":            ch.Effort,
		})
	}

	if rec != nil {
		return map[string]any{
			"id":                rec.ID,
			"type":              rec.WorkItemType,
			"title":             rec.Title,
			"state":             rec.State,
			"reason":            rec.Reason,
			"assigned_to":       rec.AssignedToName,
			"assigned_email":    rec.AssignedToEmail,
			"activity":          rec.Activity,
			"original_estimate": rec.OriginalEstimate,
			"remaining_work":    rec.RemainingWork,
			"completed_work":    rec.CompletedWork,
			"effort":            rec.Effort,
			"story_points":      rec.StoryPoints,
			"start_date":        rec.StartDate,
			"target_date":       rec.TargetDate,
			"finish_date":       rec.FinishDate,
			"description":       rec.Description,
			"parent_id":         rec.ParentID,
			"tags":              rec.Tags,
			"area_path":         rec.AreaPath,
			"iteration_path":    rec.IterationPath,
			"url":               rec.URL,
			"children_count":    len(children),
			"children":          childSummaries,
		}, nil
	}

	return map[string]any{
		"id":                item.ID,
		"type":              item.Type(),
		"title":             item.Title(),
		"state":             item.State(),
		"assigned_to":       item.AssignedTo(),
		"activity":          item.Activity(),
		"original_estimate": item.OriginalEstimate(),
		"remaining_work":    item.RemainingWork(),
		"completed_work":    item.CompletedWork(),
		"effort":            item.Effort(),
		"description":       item.Description(),
		"parent_id":         item.ParentID(),
		"children_count":    len(item.ChildIDs()),
		"child_ids":         item.ChildIDs(),
	}, nil
}

func (e *Executor) executeGetChildren(args map[string]any) (map[string]any, error) {
	idVal, ok := args["work_item_id"]
	if !ok {
		return nil, fmt.Errorf("missing required parameter: work_item_id")
	}
	id := toInt(idVal)
	if id == 0 && e.Context != nil && e.Context.SelectedItem != nil {
		id = e.Context.SelectedItem.ID
	}
	if id <= 0 {
		return nil, fmt.Errorf("invalid work_item_id: %v", idVal)
	}

	recursive := true
	if rVal, exists := args["recursive"]; exists {
		recursive = toBool(rVal)
	}

	format := getString(args, "format")
	if format == "" {
		format = "tree"
	}
	format = strings.ToLower(format)

	refresh := getBool(args, "refresh")

	// 1. If refresh requested, sync from ADO
	if refresh && e.AdoClient != nil {
		if items, err := e.AdoClient.FetchHierarchy(id); err == nil && len(items) > 0 && e.DB != nil {
			_ = e.DB.SaveWorkItems(e.AdoClient.Org, e.AdoClient.Project, items)
		}
	}

	var rootRec *db.WorkItemRecord
	if e.DB != nil {
		rootRec, _ = e.DB.GetWorkItem(id)
	}

	// Fallback to ADO fetch if not found in DB
	if rootRec == nil && e.AdoClient != nil {
		if items, err := e.AdoClient.FetchHierarchy(id); err == nil && len(items) > 0 {
			if e.DB != nil {
				_ = e.DB.SaveWorkItems(e.AdoClient.Org, e.AdoClient.Project, items)
				rootRec, _ = e.DB.GetWorkItem(id)
			}
		} else if item, err := e.AdoClient.GetWorkItem(id); err == nil && item != nil {
			if e.DB != nil {
				_ = e.DB.SaveWorkItem(e.AdoClient.Org, e.AdoClient.Project, item)
				rootRec, _ = e.DB.GetWorkItem(id)
			}
		}
	}

	if rootRec == nil {
		return nil, fmt.Errorf("work item #%d not found", id)
	}

	var targetItems []*db.WorkItemRecord
	if recursive {
		if e.DB != nil {
			targetItems, _ = e.DB.GetDescendantWorkItems(id)
		}
		if len(targetItems) == 0 && !refresh && e.AdoClient != nil {
			if items, err := e.AdoClient.FetchHierarchy(id); err == nil && len(items) > 1 {
				if e.DB != nil {
					_ = e.DB.SaveWorkItems(e.AdoClient.Org, e.AdoClient.Project, items)
					targetItems, _ = e.DB.GetDescendantWorkItems(id)
				}
			}
		}
	} else {
		if e.DB != nil {
			targetItems, _ = e.DB.GetChildWorkItems(id)
		}
		if len(targetItems) == 0 && !refresh && e.AdoClient != nil {
			if items, err := e.AdoClient.FetchHierarchy(id); err == nil && len(items) > 1 {
				if e.DB != nil {
					_ = e.DB.SaveWorkItems(e.AdoClient.Org, e.AdoClient.Project, items)
					targetItems, _ = e.DB.GetChildWorkItems(id)
				}
			}
		}
	}

	// Calculate rollup estimates & counts
	var origEst, remWork, compWork, effort float64
	countsByType := make(map[string]int)
	countsByState := make(map[string]int)

	for _, it := range targetItems {
		origEst += it.OriginalEstimate
		remWork += it.RemainingWork
		compWork += it.CompletedWork
		effort += it.Effort
		countsByType[it.WorkItemType]++
		countsByState[it.State]++
	}

	treeNode := db.BuildSingleTree(rootRec, targetItems)
	hierarchyNode := treeNode.ToHierarchyNode()

	result := map[string]any{
		"work_item_id":    id,
		"parent":          rootRec,
		"recursive":       recursive,
		"total_children":  len(targetItems),
		"counts_by_type":  countsByType,
		"counts_by_state": countsByState,
		"rollup_estimates": map[string]float64{
			"original_estimate_hours": origEst,
			"remaining_work_hours":    remWork,
			"completed_work_hours":    compWork,
			"effort_points":           effort,
		},
	}

	if format == "tree" {
		if hierarchyNode != nil && len(hierarchyNode.Children) > 0 {
			result["children"] = hierarchyNode.Children
		} else {
			result["children"] = []any{}
		}
	} else if format == "flat" {
		result["children"] = targetItems
	} else { // "both"
		if hierarchyNode != nil && len(hierarchyNode.Children) > 0 {
			result["children"] = hierarchyNode.Children
		} else {
			result["children"] = []any{}
		}
		result["items"] = targetItems
	}

	return result, nil
}

func (e *Executor) executeGetHierarchy(args map[string]any) (map[string]any, error) {
	idVal, ok := args["work_item_id"]
	if !ok {
		return nil, fmt.Errorf("missing required parameter: work_item_id")
	}
	id := toInt(idVal)
	if id == 0 && e.Context != nil && e.Context.SelectedItem != nil {
		id = e.Context.SelectedItem.ID
	}
	if id <= 0 {
		return nil, fmt.Errorf("invalid work_item_id: %v", idVal)
	}

	includeAncestors := true
	if aVal, exists := args["include_ancestors"]; exists {
		includeAncestors = toBool(aVal)
	}

	refresh := getBool(args, "refresh")

	// 1. If refresh requested, sync from ADO
	if refresh && e.AdoClient != nil {
		if items, err := e.AdoClient.FetchHierarchy(id); err == nil && len(items) > 0 && e.DB != nil {
			_ = e.DB.SaveWorkItems(e.AdoClient.Org, e.AdoClient.Project, items)
		}
	}

	var rootRec *db.WorkItemRecord
	if e.DB != nil {
		rootRec, _ = e.DB.GetWorkItem(id)
	}

	if rootRec == nil && e.AdoClient != nil {
		if items, err := e.AdoClient.FetchHierarchy(id); err == nil && len(items) > 0 {
			if e.DB != nil {
				_ = e.DB.SaveWorkItems(e.AdoClient.Org, e.AdoClient.Project, items)
				rootRec, _ = e.DB.GetWorkItem(id)
			}
		} else if item, err := e.AdoClient.GetWorkItem(id); err == nil && item != nil {
			if e.DB != nil {
				_ = e.DB.SaveWorkItem(e.AdoClient.Org, e.AdoClient.Project, item)
				rootRec, _ = e.DB.GetWorkItem(id)
			}
		}
	}

	if rootRec == nil {
		return nil, fmt.Errorf("work item #%d not found", id)
	}

	var ancestors []*db.WorkItemRecord
	if includeAncestors && e.DB != nil {
		ancestors, _ = e.DB.GetAncestorWorkItems(id)
	}

	var descendants []*db.WorkItemRecord
	if e.DB != nil {
		descendants, _ = e.DB.GetDescendantWorkItems(id)
	}

	if len(descendants) == 0 && !refresh && e.AdoClient != nil {
		if items, err := e.AdoClient.FetchHierarchy(id); err == nil && len(items) > 1 {
			if e.DB != nil {
				_ = e.DB.SaveWorkItems(e.AdoClient.Org, e.AdoClient.Project, items)
				descendants, _ = e.DB.GetDescendantWorkItems(id)
			}
		}
	}

	// Calculate rollup estimates & counts
	var origEst, remWork, compWork, effort float64
	countsByType := make(map[string]int)
	countsByState := make(map[string]int)

	for _, it := range descendants {
		origEst += it.OriginalEstimate
		remWork += it.RemainingWork
		compWork += it.CompletedWork
		effort += it.Effort
		countsByType[it.WorkItemType]++
		countsByState[it.State]++
	}

	treeNode := db.BuildSingleTree(rootRec, descendants)
	hierarchyNode := treeNode.ToHierarchyNode()

	result := map[string]any{
		"work_item_id":      id,
		"item":              rootRec,
		"ancestors":         ancestors,
		"total_descendants": len(descendants),
		"counts_by_type":    countsByType,
		"counts_by_state":   countsByState,
		"rollup_estimates": map[string]float64{
			"original_estimate_hours": origEst,
			"remaining_work_hours":    remWork,
			"completed_work_hours":    compWork,
			"effort_points":           effort,
		},
		"tree":        hierarchyNode,
		"descendants": descendants,
	}

	return result, nil
}

func (e *Executor) executeUpdateWorkItem(args map[string]any) (map[string]any, error) {
	idVal, ok := args["work_item_id"]
	if !ok {
		return nil, fmt.Errorf("missing required parameter: work_item_id")
	}
	id := toInt(idVal)
	if id == 0 && e.Context.SelectedItem != nil {
		id = e.Context.SelectedItem.ID
	}

	fields := make(map[string]any)
	if state, ok := args["state"].(string); ok && state != "" {
		fields["System.State"] = state
	}
	if title, ok := args["title"].(string); ok && title != "" {
		fields["System.Title"] = title
	}
	if assignedTo, ok := args["assigned_to"].(string); ok && assignedTo != "" {
		resolved := e.resolveAssignee(assignedTo)
		fields["System.AssignedTo"] = resolved
	}
	var origVal *float64
	var remVal *float64
	var compVal *float64

	effField := "Microsoft.VSTS.Scheduling.Effort"
	origField := "Microsoft.VSTS.Scheduling.OriginalEstimate"
	remField := "Microsoft.VSTS.Scheduling.RemainingWork"
	compField := "Microsoft.VSTS.Scheduling.CompletedWork"
	startField := "Microsoft.VSTS.Scheduling.StartDate"
	targetField := "Microsoft.VSTS.Scheduling.TargetDate"
	finishField := "Microsoft.VSTS.Scheduling.FinishDate"

	var recItem *db.WorkItemRecord
	if e.DB != nil {
		if rec, err := e.DB.GetWorkItem(id); err == nil && rec != nil {
			recItem = rec
			if ref, ok := e.DB.TypeGetEffortField(rec.Org, rec.Project, rec.WorkItemType); ok {
				effField = ref
			}
			if ref, ok := e.DB.TypeGetEstimateField(rec.Org, rec.Project, rec.WorkItemType); ok {
				origField = ref
			}
			if ref, ok := e.DB.TypeGetRemainingWorkField(rec.Org, rec.Project, rec.WorkItemType); ok {
				remField = ref
			}
			if ref, ok := e.DB.TypeGetCompletedWorkField(rec.Org, rec.Project, rec.WorkItemType); ok {
				compField = ref
			}
			if ref, ok := e.DB.TypeGetStartDateField(rec.Org, rec.Project, rec.WorkItemType); ok {
				startField = ref
			}
			if ref, ok := e.DB.TypeGetTargetDateField(rec.Org, rec.Project, rec.WorkItemType); ok {
				targetField = ref
			}
			if ref, ok := e.DB.TypeGetFinishDateField(rec.Org, rec.Project, rec.WorkItemType); ok {
				finishField = ref
			}
		}
	}

	if est, ok := args["original_estimate"]; ok && est != nil {
		val := toFloat(est)
		origVal = &val
		fields[origField] = val
	}
	if rem, ok := args["remaining_work"]; ok && rem != nil {
		val := toFloat(rem)
		remVal = &val
		fields[remField] = val
	}
	if comp, ok := args["completed_work"]; ok && comp != nil {
		val := toFloat(comp)
		compVal = &val
		fields[compField] = val
	}
	if effort, ok := args["effort"]; ok && effort != nil {
		val := toFloat(effort)
		fields[effField] = val
	}
	if desc, ok := args["description"].(string); ok && desc != "" {
		fields["System.Description"] = desc
	}
	if tags, ok := args["tags"].(string); ok {
		fields["System.Tags"] = tags
	}
	if activity, ok := args["activity"].(string); ok {
		fields["Microsoft.VSTS.Common.Activity"] = activity
	}
	if iter, ok := args["iteration_path"].(string); ok && iter != "" {
		fields["System.IterationPath"] = iter
	}
	if area, ok := args["area_path"].(string); ok && area != "" {
		fields["System.AreaPath"] = area
	}
	if s, ok := parseFlexibleDateField(args["start_date"]); ok {
		fields[startField] = s
	}
	if s, ok := parseFlexibleDateField(args["target_date"]); ok {
		fields[targetField] = s
	}
	if s, ok := parseFlexibleDateField(args["finish_date"]); ok {
		fields[finishField] = s
	}

	// Auto-calculate remaining work = original - completed if remaining_work was not explicitly provided
	if remVal == nil && (origVal != nil || compVal != nil) {
		var curOrig, curComp float64
		if recItem != nil {
			curOrig = recItem.OriginalEstimate
			curComp = recItem.CompletedWork
		}
		if origVal != nil {
			curOrig = *origVal
		}
		if compVal != nil {
			curComp = *compVal
		}
		calcRem := curOrig - curComp
		if calcRem < 0 {
			calcRem = 0
		}
		fields[remField] = calcRem
	}

	// Auto-set finish date if transition to Done / completed and finish_date was not explicitly specified
	if _, finishSpecified := fields[finishField]; !finishSpecified {
		if newState, ok := fields["System.State"].(string); ok && newState != "" {
			autoFinish := true
			if e.Context != nil && e.Context.CurrentSettings != nil {
				autoFinish = e.Context.CurrentSettings.AutoSetFinishDate
			} else if e.DB != nil {
				if v, err := e.DB.GetSetting("auto_set_finish_date"); err == nil && v != "" {
					autoFinish = (v == "true" || v == "1")
				}
			}
			if autoFinish {
				isDone := false
				if e.DB != nil && recItem != nil {
					isDone = e.DB.IsStateCompleted(recItem.Org, recItem.Project, recItem.WorkItemType, newState)
				} else {
					isDone = ado.IsStateDoneOrClosed(newState)
				}
				if isDone {
					fields[finishField] = ado.FormatAdoDateTime(time.Now())
				}
			}
		}
	}

	if len(fields) == 0 {
		return map[string]any{"status": "no changes specified", "work_item_id": id}, nil
	}

	updatedItem, err := e.AdoClient.UpdateWorkItemFields(id, fields)
	if err != nil {
		return nil, fmt.Errorf("failed to update work item #%d: %w", id, err)
	}

	_ = e.DB.SaveWorkItem(e.AdoClient.Org, e.AdoClient.Project, updatedItem)
	e.AffectedIDs[id] = true

	return map[string]any{
		"status":            "success",
		"work_item_id":      id,
		"title":             updatedItem.Title(),
		"state":             updatedItem.State(),
		"activity":          updatedItem.Activity(),
		"remaining_work":    updatedItem.RemainingWork(),
		"original_estimate": updatedItem.OriginalEstimate(),
		"completed_work":    updatedItem.CompletedWork(),
		"assigned_to":       updatedItem.AssignedTo(),
		"start_date":        updatedItem.StartDate(),
		"target_date":       updatedItem.TargetDate(),
		"finish_date":       updatedItem.FinishDate(),
	}, nil
}

