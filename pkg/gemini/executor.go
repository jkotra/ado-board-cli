func (e *Executor) executeGetUsers(args map[string]any) (map[string]any, error) {
	query := getString(args, "query")
	limit := toInt(args["limit"])
	if limit <= 0 {
		limit = 50
	}

	seen := make(map[string]bool)
	type userEntry struct {
		DisplayName string `json:"display_name"`
		Email       string `json:"email"`
		ID          string `json:"id,omitempty"`
	}
	var users []userEntry

	// 1. Try DB identities
	if e.DB != nil {
		if identities, err := e.DB.SearchIdentities(query, limit); err == nil && len(identities) > 0 {
			for _, id := range identities {
				key := strings.ToLower(strings.TrimSpace(id.Email))
				if key == "" {
					key = strings.ToLower(strings.TrimSpace(id.DisplayName))
				}
				if key != "" && !seen[key] {
					seen[key] = true
					users = append(users, userEntry{
						DisplayName: id.DisplayName,
						Email:       id.Email,
						ID:          id.ID,
					})
				}
			}
		}

		// Also distinct assignees from DB work items
		if len(users) < limit {
			if assignees, err := e.DB.GetDistinctAssignees(); err == nil {
				for _, a := range assignees {
					if query != "" {
						qLower := strings.ToLower(query)
						if !strings.Contains(strings.ToLower(a.DisplayName), qLower) && !strings.Contains(strings.ToLower(a.Email), qLower) {
							continue
						}
					}
					key := strings.ToLower(strings.TrimSpace(a.Email))
					if key == "" {
						key = strings.ToLower(strings.TrimSpace(a.DisplayName))
					}
					if key != "" && !seen[key] {
						seen[key] = true
						users = append(users, userEntry{
							DisplayName: a.DisplayName,
							Email:       a.Email,
						})
					}
				}
			}
		}
	}

	// 2. Try Context cached identities
	if e.Context != nil && len(users) < limit {
		for _, id := range e.Context.CachedIdentities {
			if query != "" {
				qLower := strings.ToLower(query)
				if !strings.Contains(strings.ToLower(id.DisplayName), qLower) && !strings.Contains(strings.ToLower(id.Email), qLower) {
					continue
				}
			}
			key := strings.ToLower(strings.TrimSpace(id.Email))
			if key == "" {
				key = strings.ToLower(strings.TrimSpace(id.DisplayName))
			}
			if key != "" && !seen[key] {
				seen[key] = true
				users = append(users, userEntry{
					DisplayName: id.DisplayName,
					Email:       id.Email,
				})
			}
		}
	}

	// 3. Fallback to ADO API if DB and Context have no identities and client is available
	if len(users) == 0 && e.AdoClient != nil {
		if members, err := e.AdoClient.FetchProjectTeamMembers(); err == nil && len(members) > 0 {
			if e.DB != nil {
				_ = e.DB.SaveIdentities(members)
			}
			for _, m := range members {
				if query != "" {
					qLower := strings.ToLower(query)
					if !strings.Contains(strings.ToLower(m.DisplayName), qLower) && !strings.Contains(strings.ToLower(m.UniqueName), qLower) {
						continue
					}
				}
				key := strings.ToLower(strings.TrimSpace(m.UniqueName))
				if key == "" {
					key = strings.ToLower(strings.TrimSpace(m.DisplayName))
				}
				if key != "" && !seen[key] {
					seen[key] = true
					users = append(users, userEntry{
						DisplayName: m.DisplayName,
						Email:       m.UniqueName,
						ID:          m.ID,
					})
				}
			}
		}
	}

	return map[string]any{
		"total_users": len(users),
		"users":       users,
	}, nil
}

func (e *Executor) executeRenameTab(args map[string]any) (map[string]any, error) {
	newName := strings.TrimSpace(getString(args, "new_name"))
	if newName == "" {
		return nil, fmt.Errorf("new_name is required")
	}
	tabIdx := toInt(args["tab_index"])
	rootID := toInt(args["root_id"])
	tabName := getString(args, "tab_name")

	// Try IPC first if TUI is running
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
	defer cancel()
	resp, err := ipc.SendCommand(ctx, ipc.Request{
		Command:  ipc.CmdRenameTab,
		TabIndex: tabIdx,
		RootID:   rootID,
		TabName:  tabName,
		NewName:  newName,
	})
	if err == nil && resp.Success {
		return map[string]any{
			"success":  true,
			"status":   "success",
			"message":  resp.Message,
			"new_name": newName,
		}, nil
	}

	// Fallback to SQLite persistence if offline
	if e.DB != nil {
		if rootID > 0 {
			if err := e.DB.UpdateTrackedRootCustomTitle(rootID, newName); err != nil {
				return nil, fmt.Errorf("failed to update root tab name: %w", err)
			}
			return map[string]any{
				"success":  true,
				"status":   "success",
				"root_id":  rootID,
				"new_name": newName,
				"message":  fmt.Sprintf("Renamed root #%d tab to %q (saved to database)", rootID, newName),
			}, nil
		}
		if tabName != "" {
			if queries, err := e.DB.GetTrackedQueries(); err == nil {
				for _, q := range queries {
					if strings.EqualFold(q.Name, tabName) {
						_ = e.DB.UpdateTrackedQueryName(q.ID, newName)
						return map[string]any{
							"success":  true,
							"status":   "success",
							"query_id": q.ID,
							"new_name": newName,
							"message":  fmt.Sprintf("Renamed query tab to %q (saved to database)", newName),
						}, nil
					}
				}
			}
		}
	}

	return map[string]any{
		"success":  true,
		"status":   "success",
		"new_name": newName,
		"message":  fmt.Sprintf("Tab renamed to %q", newName),
	}, nil
}

